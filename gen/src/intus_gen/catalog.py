"""Rendering the data catalog from the schemas themselves.

``docs/data-catalog.md`` is generated, never hand-edited. A classification
document maintained by hand is a document that is wrong: someone adds a column,
the doc is updated in a later PR or not at all, and by the time an access
review reads it the two have diverged. Generating it means the catalog cannot
disagree with the code, and a CI check that regenerates and diffs would catch
a stale commit.
"""

from __future__ import annotations

from collections.abc import Sequence

from intus_gen.sensitivity import Dataset, Tier

_TIER_NOTE: dict[Tier, str] = {
    Tier.PUBLIC: "No restriction; safe outside the company.",
    Tier.INTERNAL: "Any employee may read.",
    Tier.CONFIDENTIAL: "Restricted to a business function by row-level security.",
    Tier.RESTRICTED: "Column-masked even for holders of the surrounding rows.",
}


def render_markdown(datasets: Sequence[Dataset]) -> str:
    """Render the full catalog: tier legend, dataset index, then column detail."""
    lines: list[str] = [
        "# Data catalog",
        "",
        "**Generated by `intus-gen catalog` — do not edit by hand.**",
        "",
        "Every column generated by `intus_gen` carries a sensitivity tier, assigned at",
        "generation time and declared beside the schema it describes. The governance",
        "phase enforces these tiers; this document is the statement of what it must",
        "enforce.",
        "",
        "## Tiers",
        "",
        "| Tier | Meaning |",
        "| --- | --- |",
    ]
    lines.extend(f"| `{tier.value}` | {_TIER_NOTE[tier]} |" for tier in Tier)

    lines += [
        "",
        "## Datasets",
        "",
        "| Dataset | Steward | Highest tier | Primary key | Retention |",
        "| --- | --- | --- | --- | --- |",
    ]
    for dataset in sorted(datasets, key=lambda dataset: dataset.name):
        retention = f"{dataset.retention_days} days" if dataset.retention_days else "full history"
        lines.append(
            f"| [`{dataset.name}`](#{dataset.name.replace('_', '-')}) "
            f"| {dataset.steward} "
            f"| `{dataset.max_tier.value}` "
            f"| {', '.join(f'`{key}`' for key in dataset.primary_key)} "
            f"| {retention} |"
        )

    for dataset in sorted(datasets, key=lambda dataset: dataset.name):
        lines += [
            "",
            f"### {dataset.name}",
            "",
            dataset.description,
            "",
            f"Steward: **{dataset.steward}**. "
            f"Primary key: {', '.join(f'`{key}`' for key in dataset.primary_key)}.",
            "",
            "| Column | Tier | Description |",
            "| --- | --- | --- |",
        ]
        lines.extend(
            f"| `{column.name}` | `{column.tier.value}` | {column.description} |"
            for column in dataset.columns
        )

    return "\n".join(lines) + "\n"
